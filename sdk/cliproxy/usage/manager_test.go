func TestRecordOmittedGenerateIsEnabled(t *testing.T) {
	// Existing callers construct Record without setting Generate.
	// Omission must remain distinguishable from explicit false and default to true.
	record := Record{
		Provider: "openai",
		Model:    "gpt-5.4",
	}
	if record.Generate != nil {
		t.Fatalf("Record.Generate = %v, want nil for omitted field", record.Generate)
	}
	if !GenerateEnabled(record.Generate) {
		t.Fatalf("GenerateEnabled(omitted) = false, want true")
	}
}

type slowCountingPlugin struct {
	mu    sync.Mutex
	count int
}

func (p *slowCountingPlugin) HandleUsage(context.Context, Record) {
	time.Sleep(time.Millisecond)
	p.mu.Lock()
	p.count++
	p.mu.Unlock()
}

func TestWaitDeliversQueuedRecordsAfterStop(t *testing.T) {
	m := NewManager(0)
	plugin := &slowCountingPlugin{}
	m.Register(plugin)
	m.Start(context.Background())
	for i := 0; i < 50; i++ {
		m.Publish(context.Background(), Record{Model: "m"})
	}
	m.Stop()
	if err := m.Wait(context.Background()); err != nil {
		t.Fatalf("Wait: %v", err)
	}

	plugin.mu.Lock()
	defer plugin.mu.Unlock()
	if plugin.count != 50 {
		t.Fatalf("delivered %d records before Wait returned, want 50", plugin.count)
	}
}
